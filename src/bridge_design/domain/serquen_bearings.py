@dataclass(frozen=True)
class CatalogRow:
    family: str
    page: int
    short_mm: int
    long_mm: int
    rubber_mm: int
    steel_mm: int
    road_capacity_kn: float
    # (n zunchos, rotación máxima en milirradianes), solo casillas legibles impresas.
    rotations: tuple

    @property
    def identifier(self):
        return f"Serquen-p{self.page}-{self.family}-{self.short_mm}x{self.long_mm}-{self.rubber_mm}+{self.steel_mm}"


def _rots(start, values):
    return tuple((start+j,v) for j,v in enumerate(values))


